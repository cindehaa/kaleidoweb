#!/usr/bin/env node
/* ══════════════════════════════════════════════════════════════════
   runtime/tools/bundle.mjs — the file:// shim.

   Chromium refuses fetch(), XHR and ES-module imports across file://
   origins, so an offline test page cannot READ its own spec or its
   Content Model.  In the extension both arrive over the wire (the spec
   as a token stream, the Content Model from the live DOM), which is
   what `interpreter.js` is written against — `KW.Source.fromStream()`.

   This tool therefore does exactly one thing: it copies the canonical
   inputs into one classic <script> so the same interpreter can be
   driven by `KW.Source.fromText()` with no code path changed.

   It also performs the parts of `imageCensus` / media extraction that
   the live extension gets for free from the rendered DOM — the gallery
   `alt` text and each file's intrinsic pixel size — because
   benchmarks/hokusai/content-model.json does not carry them.

     node runtime/tools/bundle.mjs
   ══════════════════════════════════════════════════════════════════ */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '../..');
const B = (p) => resolve(ROOT, 'benchmarks/hokusai', p);

const contentModel = JSON.parse(readFileSync(B('content-model.json'), 'utf8'));
const semantic = JSON.parse(readFileSync(B('semantic.json'), 'utf8'));
const mediaList = JSON.parse(readFileSync(B('media-list.json'), 'utf8'));
const source = readFileSync(B('source.html'), 'utf8');

/* ---- what the live DOM would hand the extractor: alt text + true pixels ---- */
const perFile = {};
for (const tag of source.match(/<img\b[^>]*>/g) || []) {
  const res = /resource="\.\/(File:[^"]+)"/.exec(tag);
  if (!res) continue;
  const key = decodeURIComponent(res[1]);
  if (perFile[key]) continue;
  const w = /data-file-width="(\d+)"/.exec(tag);
  const h = /data-file-height="(\d+)"/.exec(tag);
  const alt = /\salt="([^"]*)"/.exec(tag);
  perFile[key] = {
    w: w ? +w[1] : null,
    h: h ? +h[1] : null,
    alt: alt && alt[1] ? decodeEntities(alt[1]) : null,
  };
}

/* which files sit inside the article's own <ul class="gallery"> */
const galleryFiles = new Set();
{
  const start = source.indexOf('<ul class="gallery');
  if (start > -1) {
    const end = source.indexOf('</ul>', start);
    const blk = source.slice(start, end);
    for (const m of blk.matchAll(/resource="\.\/(File:[^"]+)"/g)) {
      galleryFiles.add(decodeURIComponent(m[1]));
    }
  }
}

function decodeEntities(s) {
  return s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&nbsp;/g, ' ');
}

/* local asset files: NN-slug.ext, index-aligned with contentModel.images */
const assetDir = resolve(ROOT, 'experiences/hokusai/assets');
const local = readdirSync(assetDir).filter((f) => /^\d\d-.*\.(jpg|png|jpeg|webp)$/i.test(f)).sort();

const keyOf = (f) => {
  if (perFile[f]) return f;
  const alt = f.replace(/ /g, '_');
  if (perFile[alt]) return alt;
  const alt2 = f.replace(/_/g, ' ');
  return perFile[alt2] ? alt2 : f;
};

contentModel.images = contentModel.images.map((im, i) => {
  const k = keyOf(im.file);
  const extra = perFile[k] || {};
  return {
    ...im,
    idx: i,
    local: local[i] || null,
    alt: extra.alt || null,
    w: extra.w || null,
    h: extra.h || null,
    gallery: galleryFiles.has(k) || galleryFiles.has(im.file),
    lead: i === 0 || !!(mediaList.items[i] && mediaList.items[i].leadImage),
  };
});

/* trim media-list to what the runtime actually joins against */
const media = {
  revision: mediaList.revision,
  items: mediaList.items.map((it) => ({ title: it.title, section_id: it.section_id, leadImage: !!it.leadImage })),
};

const spec = readFileSync(resolve(HERE, '../specs/hokusai.ndjson'), 'utf8');

const out = `/* GENERATED by runtime/tools/bundle.mjs — do not edit.
   Canonical sources: runtime/specs/hokusai.ndjson, benchmarks/hokusai/*.
   Exists only because file:// forbids fetch(); over http the interpreter
   streams the same bytes through KW.Source.fromStream(). */
window.KW_BUNDLE = ${JSON.stringify({
  subject: 'hokusai',
  spec,
  data: { contentModel, semantic, media },
}, null, 0)};
`;

const target = resolve(HERE, '../specs/hokusai.bundle.js');
writeFileSync(target, out);
console.log(`wrote ${target} — ${(out.length / 1024).toFixed(1)} kB · spec ${spec.split('\n').filter(Boolean).length} records · ${contentModel.images.length} images (${local.length} local)`);
